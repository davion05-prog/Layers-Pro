"use client";

import { useCallback, useEffect, useState, type FormEvent } from "react";
import { security } from "../lib/session";
import { Badge, Field, Modal, Panel, Table } from "./ui";

type Activity = { id: string; event: string; occurred_at: string };
type Enrollment = { id: string; qr: string; key: string };

export function SecurityPanel({
  online,
  clearDevice,
  signOutAll,
}: {
  online: boolean;
  clearDevice: () => void;
  signOutAll: () => Promise<void>;
}) {
  const [events, setEvents] = useState<Activity[]>([]);
  const [enabled, setEnabled] = useState<boolean>();
  const [enrollment, setEnrollment] = useState<Enrollment>();
  const [message, setMessage] = useState("");
  const [busy, setBusy] = useState(false);
  const [confirm, setConfirm] = useState<"remove" | "all">();

  const refresh = useCallback(async () => {
    try {
      const data = await security<{ events: Activity[]; enabled: boolean }>();
      setEvents(data.events);
      setEnabled(data.enabled);
    } catch (error) {
      setMessage(
        error instanceof Error
          ? error.message
          : "Could not load account security.",
      );
    }
  }, []);
  useEffect(() => {
    if (online) void refresh();
  }, [online, refresh]);

  async function action(
    kind: "enroll" | "verify" | "cancel" | "remove",
    code?: string,
  ) {
    setBusy(true);
    setMessage("");
    try {
      const result = await security<Enrollment>({
        action: kind,
        factor: enrollment?.id,
        code,
      });
      if (kind === "enroll") setEnrollment(result);
      else {
        setEnrollment(undefined);
        setConfirm(undefined);
        await refresh();
      }
    } catch (error) {
      setMessage(
        error instanceof Error
          ? error.message
          : "Could not update account security.",
      );
    } finally {
      setBusy(false);
    }
  }

  function verify(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    void action(
      "verify",
      String(new FormData(event.currentTarget).get("code")),
    );
  }

  return (
    <>
      <Panel
        title="Account security"
        description={
          online
            ? "Manage your authenticator, devices and sign-in activity."
            : "Connect to the internet to view account security."
        }
      >
        <div className="settings-actions">
          {enabled !== undefined && (
            <button
              className="button secondary"
              disabled={!online || busy}
              onClick={() =>
                enabled ? setConfirm("remove") : void action("enroll")
              }
            >
              {enabled ? "Remove authenticator" : "Set up an authenticator"}
            </button>
          )}
          <button
            className="button secondary"
            disabled={!online || busy}
            onClick={() => setConfirm("all")}
          >
            Sign out all devices
          </button>
          <button className="button secondary" onClick={clearDevice}>
            Clear data from this device
          </button>
        </div>
        {message && !enrollment && (
          <p className="form-warning" role="status">
            {message}
          </p>
        )}
        <Table
          headers={["Recent activity", "Time"]}
          rows={events.map((event) => [
            event.event === "New device sign-in" ? (
              <Badge key={event.id} tone="amber">
                {event.event}
              </Badge>
            ) : (
              event.event
            ),
            new Date(event.occurred_at).toLocaleString(),
          ])}
        />
      </Panel>
      {enrollment && (
        <Modal
          title="Set up your authenticator"
          onClose={() => void action("cancel")}
        >
          <p>
            Scan the QR code in your authenticator app, then enter its six-digit
            code.
          </p>
          {/* The QR image is generated by Supabase and rendered locally without a third-party request. */}
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img
            className="mfa-qr"
            width={180}
            height={180}
            alt="Authenticator setup QR code"
            src={
              enrollment.qr.startsWith("data:image/")
                ? enrollment.qr
                : "data:image/svg+xml," + encodeURIComponent(enrollment.qr)
            }
          />
          <details>
            <summary>Enter a setup key manually</summary>
            <code>{enrollment.key}</code>
          </details>
          <form className="editor-form" onSubmit={verify}>
            <Field label="Authenticator code">
              <input
                name="code"
                inputMode="numeric"
                autoComplete="one-time-code"
                pattern="[0-9]{6}"
                maxLength={6}
                required
              />
            </Field>
            {message && (
              <p className="form-error" role="alert">
                {message}
              </p>
            )}
            <button className="button primary" disabled={busy}>
              Verify and enable
            </button>
          </form>
        </Modal>
      )}
      {confirm && (
        <Modal
          title={
            confirm === "all"
              ? "Sign out all devices"
              : "Remove your authenticator"
          }
          onClose={() => setConfirm(undefined)}
        >
          <p>
            {confirm === "all"
              ? "This ends your online sessions on all devices. Devices that are offline can keep their downloaded records until they reconnect."
              : "You will log in with your password after removing this authenticator."}
          </p>
          <button
            className="button danger"
            disabled={busy}
            onClick={async () => {
              if (confirm === "remove") void action("remove");
              else {
                setConfirm(undefined);
                await signOutAll();
              }
            }}
          >
            {confirm === "all"
              ? "Sign out all devices"
              : "Remove authenticator"}
          </button>
        </Modal>
      )}
    </>
  );
}
